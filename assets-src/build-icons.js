// Bundles only the Lucide icons the admin uses into admin/js/icons.js.
// An icon is "used" when the admin code names it as data-lucide="name" or
// icon('name'...). Run with `npm run build:icons`.
const fs = require('fs');
const path = require('path');
const { icons } = require('lucide');

const root = path.resolve(__dirname, '..', 'admin');
const files = [];
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/\.(php|js)$/.test(entry.name) && entry.name !== 'icons.js') files.push(full);
  }
})(root);

const pascal = name => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

// Strict: a name in these spots must be a Lucide icon (a typo fails the build).
// Loose: any quoted word inside icon(...) or btn(...) / actionButton(...)
// calls - covers `icon(done ? 'circle-check' : 'circle')` and
// `btn('edit-course', 'pencil', ...)` - kept only when it is a Lucide icon.
const strict = [/data-lucide=["']([a-z0-9-]+)["']/g, /\bicon\(\s*["']([a-z0-9-]+)["']/g];
const calls = /\b(?:icon|btn|actionButton)\(([^()]*(?:\([^()]*\)[^()]*)*)\)/g;
const names = new Set();
for (const file of files) {
  const src = fs.readFileSync(file, 'utf8');
  for (const re of strict) for (const m of src.matchAll(re)) names.add(m[1]);
  // Icon names kept in lookup tables: { icon: 'folder' }.
  for (const m of src.matchAll(/\bicon:\s*["']([a-z0-9-]+)["']/g)) if (icons[pascal(m[1])]) names.add(m[1]);
  for (const m of src.matchAll(calls)) {
    for (const q of m[1].matchAll(/["']([a-z0-9]+(?:-[a-z0-9]+)*)["']/g)) {
      if (icons[pascal(q[1])]) names.add(q[1]);
    }
  }
}
const bundle = {};
const missing = [];
for (const name of [...names].sort()) {
  const node = icons[pascal(name)];
  if (node) bundle[name] = node;
  else missing.push(name);
}

if (missing.length) {
  console.error(`Unknown Lucide icons: ${missing.join(', ')}`);
  process.exit(1);
}

const out = `/* Generated by assets-src/build-icons.js from lucide@${require('lucide/package.json').version} - do not edit. */
window.FLMS_ICONS = ${JSON.stringify(bundle)};
`;
fs.writeFileSync(path.join(root, 'js', 'icons.js'), out);
console.log(`icons.js: ${Object.keys(bundle).length} icons (${Math.round(out.length / 1024)} KB)`);
